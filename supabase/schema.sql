-- Supabase SQL Editor schema for the Bean Counter entries table.
create table if not exists public.entries (
  id bigint generated by default as identity primary key,
  week_of date not null,
  location text not null check (
    location in ('Downtown', 'Uptown', 'Design District', 'Bishop Arts')
  ),
  drinks_sold integer not null check (drinks_sold >= 0),
  revenue numeric(12, 2) not null check (revenue >= 0),
  loyalty_signups integer not null check (loyalty_signups >= 0),
  bags_sold integer not null check (bags_sold >= 0),
  notes text,
  created_at timestamptz not null default now()
);

create index if not exists entries_week_of_desc_idx
  on public.entries (week_of desc, location);

-- Keep direct client access disabled until access policies are configured.
alter table public.entries enable row level security;
